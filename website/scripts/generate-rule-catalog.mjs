import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const websiteDir = resolve(fileURLToPath(new URL('..', import.meta.url)))
const sourcePath = join(websiteDir, 'docs/reference/rules.md')
const outputDir = join(websiteDir, 'docs/reference/rules')
const dataPath = join(websiteDir, 'docs/.vitepress/theme/components/RuleCatalogData.js')
const source = readFileSync(sourcePath, 'utf8')

const headingPattern = /^#### `([^`]+)` \{#([^}]+)\}$/gm
const headings = [...source.matchAll(headingPattern)]
if (headings.length === 0) throw new Error('No rule detail headings found in docs/reference/rules.md')

function field(block, name) {
  const match = block.match(new RegExp(`^- \\*\\*${name}\\*\\*: \\x60([^\\x60]+)\\x60$`, 'm'))
  return match?.[1] || ''
}

function proseField(block, name) {
  const match = block.match(new RegExp(`^\\*\\*${name}\\*\\*: (.+)$`, 'm'))
  return match?.[1]?.trim() || ''
}

function languages(block) {
  const aliases = {
    js: 'JavaScript', jsx: 'JavaScript', ts: 'TypeScript', tsx: 'TypeScript',
    go: 'Go', python: 'Python', py: 'Python', java: 'Java', sql: 'SQL',
    json: 'JSON', yaml: 'YAML', yml: 'YAML', sh: 'Shell', bash: 'Shell'
  }
  const values = new Set()
  for (const match of block.matchAll(/^```([^\s\[]+)/gm)) {
    values.add(aliases[match[1].toLowerCase()] || match[1])
  }
  return values.size > 0 ? [...values].sort() : ['General']
}

function cleanBody(block) {
  return block
    .replace(/^#### `[^`]+` \{#[^}]+\}\s*/m, '')
    .replace(/^<p class="rule-nav">.*<\/p>\s*$/gm, '')
    .replace(/\n---\s*$/, '')
    .trim()
}

const rules = headings.map((heading, index) => {
  const start = heading.index
  const end = index + 1 < headings.length ? headings[index + 1].index : source.length
  let block = source.slice(start, end)
  const nextDomain = block.search(/^## .+ Rules \{#[^}]+\}$/m)
  if (nextDomain >= 0) block = block.slice(0, nextDomain)
  const id = heading[1]
  const slug = heading[2]
  const domain = field(block, 'Domain')
  const severity = field(block, 'Severity')
  const category = field(block, 'Category')
  const description = proseField(block, 'Description')
  if (!domain || !severity || !category || !description) {
    throw new Error(`Incomplete metadata for rule ${id}`)
  }
  return { id, slug, domain, severity, category, description, languages: languages(block), body: cleanBody(block) }
})

mkdirSync(outputDir, { recursive: true })
for (const name of readdirSync(outputDir)) {
  if (name.endsWith('.md')) rmSync(join(outputDir, name))
}

for (const [index, rule] of rules.entries()) {
  const previous = rules[index - 1]
  const next = rules[index + 1]
  const links = [
    previous ? `[← ${previous.id}](/reference/rules/${previous.slug})` : '',
    '[Rule Catalog](/reference/rule-catalog)',
    next ? `[${next.id} →](/reference/rules/${next.slug})` : ''
  ].filter(Boolean).join(' · ')
  const page = `---
title: ${JSON.stringify(`${rule.id} rule`)}
description: ${JSON.stringify(rule.description)}
---

# \`${rule.id}\`

[← Rule Catalog](/reference/rule-catalog)

${rule.body}

---

${links}
`
  writeFileSync(join(outputDir, `${rule.slug}.md`), page)
}

const publicRules = rules.map(({ body, ...rule }) => ({ ...rule, href: `/reference/rules/${rule.slug}` }))
mkdirSync(dirname(dataPath), { recursive: true })
writeFileSync(dataPath, `// Generated by scripts/generate-rule-catalog.mjs. Do not edit.\nexport const rules = ${JSON.stringify(publicRules, null, 2)}\n`)

console.log(`Generated ${rules.length} rule detail pages and catalog records.`)
